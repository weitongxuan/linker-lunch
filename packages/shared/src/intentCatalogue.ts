/** 一句話能扳動的既有開關;沒有對應開關的屬性(清淡/有湯/排隊)不假裝會篩 */
export interface IntentActions {
  excludeCat?: string[];
  cat?: string[];
  cuisine?: string[];
  excludeCuisine?: string[];
  mood?: Mood;
  mode?: 'walk' | 'drive';
  minGoogle?: number;
  service?: Service[];
  /** 具體菜名(牛肉麵、滷肉飯…):菜單裡有這道的店排前面、優先抽 */
  dish?: string[];
  /** 預算(元):菜單有價格的店,預算內要有幾道可選才留下 */
  budget?: number;
}

